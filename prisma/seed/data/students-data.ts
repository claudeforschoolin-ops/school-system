/** رقم هوية/إقامة وهمي بخانة تحقق صحيحة */
export function fakeNationalId(r: Rng, prefix: "1" | "2" = "1"): string {
  const body = prefix + Array.from({ length: 8 }, () => r.int(0, 9)).join("");
  for (let check = 0; check <= 9; check++) {
    const id = body + check;
    let sum = 0;
    for (let i = 0; i < 10; i++) {
      const d = Number(id[i]);
      if (i % 2 === 0) {
        const x = d * 2;
        sum += Math.floor(x / 10) + (x % 10);
      } else sum += d;
    }
    if (sum % 10 === 0) return id;
  }
  return body + "0";
}

let phoneSeq = 0;
